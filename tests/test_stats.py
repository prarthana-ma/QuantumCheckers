"""Wilson interval and rate statistics -- Person D's core deliverable.

Owner: **Person D -- measurement, statistics and plots**.

The expected values here are **precomputed independently**, not copied from this
implementation's own output. Three routes were used and all three agree:

* Closed form. With ``z = 1.959963984540054``, ``n = 100``, ``successes = 50``:
  ``centre = (0.5 + z^2/200) / (1 + z^2/100) = 0.5`` exactly, and
  ``margin = (z / (1 + z^2/100)) * sqrt(0.25/100 + z^2/40000) = 0.0961684696...``,
  giving ``[0.4038315304, 0.5961684696]``.
* Published tables: the standard 95% Wilson interval for 50/100 is
  ``(0.4038, 0.5962)``, matching to four decimals.
* 50-digit ``decimal.Decimal`` evaluation of the closed form, run in a scratch script
  that never imports this module.

Note that ``0/10`` and ``0/170`` have a raw lower bound of exactly ``0`` which
``decimal`` renders as ``-0.0000000000``; the table stores ``0.0``.

The values in :data:`KNOWN` are the closed-form numbers to 10 decimals. If the
implementation drifts, these fail -- which is the entire reason they are hard-coded
rather than generated by the code under test.
"""

