#: ``(successes, n, expected_low, expected_high)`` at 95% confidence.
#:
#: Chosen to cover the interesting cases: an even split, both extremes, a large sample,
#: a small sample, and a rate near but not at zero.
KNOWN: tuple[tuple[int, int, float, float], ...] = (
    # 50/100 -- textbook case, point estimate 0.5.
    (50, 100, 0.4038315304, 0.5961684696),
    # 0/10 -- zero events. Upper bound must be strictly positive: observing nothing is
    # not evidence of zero probability.
    (0, 10, 0.0000000000, 0.2775327999),
    # 10/10 -- mirror of the above; lower bound strictly below 1.
    (10, 10, 0.7224672001, 1.0000000000),
    # 1/10 -- rare event. Its mirror 9/10 must satisfy low + high == 1 exactly.
    (1, 10, 0.0178762131, 0.4041500268),
    # 9/10 -- the mirror of 1/10.
    (9, 10, 0.5958499732, 0.9821237869),
    # 170/170 -- the brief's per-condition sample size, all events.
    (170, 170, 0.9779025162, 1.0000000000),
    # 0/170 -- no events at the target sample size.
    (0, 170, 0.0000000000, 0.0220974838),
    # 45/170 -- a realistic mid rate at the target sample size.
    (45, 170, 0.2041176419, 0.3356929387),
)


@pytest.mark.parametrize(("successes", "n", "expected_low", "expected_high"), KNOWN)
def test_wilson_known_values(
    successes: int, n: int, expected_low: float, expected_high: float
) -> None:
    """Wilson interval matches independently computed values to 1e-9."""
    low, high = wilson_interval(successes, n)
    assert low == pytest.approx(expected_low, abs=1e-9)
    assert high == pytest.approx(expected_high, abs=1e-9)


def test_wilson_point_estimate_is_centred() -> None:
    """For an even split the interval is symmetric about the point estimate.

    A symmetry failure would indicate a sign or term error in the margin.
    """
    low, high = wilson_interval(50, 100)
    assert (low + high) / 2.0 == pytest.approx(0.5, abs=1e-12)
    assert low == pytest.approx(0.5 - (high - 0.5), abs=1e-12)


def test_wilson_stays_inside_unit_interval() -> None:
    """Bounds never leave ``[0, 1]``, which is the reason for using Wilson at all."""
    for successes in range(0, 11):
        for n in (1, 5, 10, 100, 170):
            if successes > n:
                continue
            low, high = wilson_interval(successes, n)
            assert 0.0 <= low <= 1.0
            assert 0.0 <= high <= 1.0
            assert low <= high


def test_wilson_interval_narrows_with_sample_size() -> None:
    """More games must not widen the interval at a fixed rate."""
    widths = []
    for n in (10, 50, 170, 1000):
        low, high = wilson_interval(round(0.4 * n), n)
        widths.append(high - low)
    assert widths == sorted(widths, reverse=True)


def test_wilson_zero_sample_is_undefined() -> None:
    """``n == 0`` yields ``(0.0, 0.0)`` and is flagged as undefined by ``Rate``."""
    assert wilson_interval(0, 0) == (0.0, 0.0)
    empty = rate(0, 0)
    assert empty.defined is False
    assert empty.point == 0.0
    assert empty.to_json()["defined"] is False


