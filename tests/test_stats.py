def test_paired_outcomes_matches_seeds_and_reuses_summary_definitions() -> None:
    a_records = [
        {"seed": 7, "winner": 0, "collapses": 2},
        {"seed": 3, "winner": None, "collapses": 0},
    ]
    b_records = [
        {"seed": 3, "winner": 1, "collapses": 1},
        {"seed": 7, "winner": 1, "collapses": 0},
    ]
    assert paired_outcomes(a_records, b_records, "win_rate_p0") == ([1, 0], [0, 0])
    assert paired_outcomes(a_records, b_records, "draw_rate") == ([0, 1], [0, 0])
    assert paired_outcomes(a_records, b_records, "collapse_rate") == ([1, 0], [0, 1])


def test_paired_outcomes_rejects_missing_mismatched_or_duplicate_seeds() -> None:
    with pytest.raises(ValueError, match="same seeds"):
        paired_outcomes([{"seed": 1}], [{"seed": 2}], "draw_rate")
    with pytest.raises(ValueError, match="duplicate seed"):
        paired_outcomes(
            [{"seed": 1}, {"seed": 1}], [{"seed": 1}, {"seed": 1}], "draw_rate"
        )
    with pytest.raises(ValueError, match="missing a seed"):
        paired_outcomes([{}], [{"seed": 1}], "draw_rate")