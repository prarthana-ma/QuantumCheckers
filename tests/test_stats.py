def test_z_for_confidence_matches_known_quantiles() -> None:
    """Inverted normal quantiles match the standard table values."""
    assert z_for_confidence(0.95) == pytest.approx(1.959963985, abs=1e-8)
    assert z_for_confidence(0.99) == pytest.approx(2.575829304, abs=1e-8)
    assert z_for_confidence(0.90) == pytest.approx(1.644853627, abs=1e-8)


def test_default_z_is_the_95_percent_quantile() -> None:
    """The module default must equal ``z_for_confidence(0.95)``."""
    assert Z_95 == pytest.approx(z_for_confidence(0.95), abs=1e-12)


def test_normal_cdf_is_symmetric_and_bounded() -> None:
    assert normal_cdf(0.0) == pytest.approx(0.5, abs=1e-15)
    # Checked against the exact 95% quantile, not the rounded 1.96: Phi(1.96) is
    # 0.9750021, so asserting 0.975 at 1e-12 would be testing the rounding.
    assert normal_cdf(z_for_confidence(0.95)) == pytest.approx(0.975, abs=1e-12)
    assert normal_cdf(z_for_confidence(0.99)) == pytest.approx(0.995, abs=1e-12)
    assert normal_cdf(-z_for_confidence(0.95)) == pytest.approx(0.025, abs=1e-12)
    assert normal_cdf(-40.0) < 1e-12
    assert normal_cdf(40.0) > 1.0 - 1e-12


def test_z_for_confidence_rejects_out_of_range() -> None:
    for bad in (0.0, 1.0, -0.5, 1.5):
        with pytest.raises(ValueError):
            z_for_confidence(bad)


