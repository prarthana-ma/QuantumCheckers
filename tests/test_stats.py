def test_compare_rates_identical_conditions_gives_zero_difference() -> None:
    """Identical inputs must give a difference of exactly zero."""
    result = compare_rates(50, 100, 50, 100)
    assert result["difference"] == pytest.approx(0.0, abs=1e-15)
    assert result["diff_low"] <= 0.0 <= result["diff_high"]


def test_compare_rates_large_gap_excludes_zero() -> None:
    """A large, well-sampled gap must have an interval excluding zero."""
    result = compare_rates(900, 1000, 100, 1000)
    assert result["difference"] == pytest.approx(0.8, abs=1e-12)
    assert result["excludes_zero"] is True
    assert result["diff_low"] > 0.0


def test_compare_rates_small_gap_includes_zero() -> None:
    """A small gap at this sample size must not be reported as separating."""
    result = compare_rates(55, 100, 50, 100)
    assert result["difference"] == pytest.approx(0.05, abs=1e-12)
    assert result["excludes_zero"] is False


def test_compare_rates_with_empty_condition_is_undefined() -> None:
    """An undersized condition must not look like a difference of zero."""
    result = compare_rates(5, 10, 0, 0)
    assert result["excludes_zero"] is False
    assert result["diff_low"] == 0.0
    assert result["diff_high"] == 0.0


def test_compare_rates_difference_stays_in_range() -> None:
    for a_s in (0, 1, 50, 99, 100):
        for b_s in (0, 1, 50, 99, 100):
            result = compare_rates(a_s, 100, b_s, 100)
            assert -1.0 <= result["diff_low"] <= 1.0
            assert -1.0 <= result["diff_high"] <= 1.0
            assert result["diff_low"] <= result["diff_high"]


def test_format_comparison_never_says_significant() -> None:
    """The formatter must not use significance language."""
    text = format_comparison("A", "B", compare_rates(90, 100, 10, 100))
    assert "significant" not in text.lower()
    assert "p=" not in text.lower()
    assert "excludes zero" in text


def test_format_comparison_handles_undefined() -> None:
    text = format_comparison("A", "B", compare_rates(5, 10, 0, 0))
    assert "undefined" in text


