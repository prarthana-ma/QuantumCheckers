def test_compare_paired_known_small_example() -> None:
    # Both marginals are 2/4; the joint success rate is 1/4, so phi=0.
    # Each Wilson interval is [0.150039, 0.849961], giving method-10 bounds
    # +/-sqrt(2*(0.5-0.150039)^2) = +/-0.494920.
    result = compare_paired([1, 1, 0, 0], [1, 0, 1, 0])
    assert result["n"] == 4
    assert result["difference"] == pytest.approx(0.0)
    assert result["lower"] == pytest.approx(-0.49491960784282796)
    assert result["upper"] == pytest.approx(0.49491960784282796)
    assert (result["b_only"], result["a_only"], result["both"], result["neither"]) == (
        1,
        1,
        1,
        1,
    )
    assert result["diff_low"] == result["lower"]
    assert result["diff_high"] == result["upper"]


def test_compare_paired_positive_correlation_narrows_interval() -> None:
    a = [1, 1, 1, 0] * 20
    b = [1, 1, 0, 0] * 20
    paired = compare_paired(a, b)
    independent = compare_rates(sum(a), len(a), sum(b), len(b))
    assert paired["a_only"] == 20
    assert paired["b_only"] == 0
    assert (paired["upper"] - paired["lower"]) < (
        independent["diff_high"] - independent["diff_low"]
    )


def test_compare_paired_independent_outcomes_roughly_match_unpaired_interval() -> None:
    # Each of the four binary pairs occurs equally often: both marginals are 0.5,
    # and the paired-difference variance approaches the independent variance.
    a = [1, 1, 0, 0] * 20
    b = [1, 0, 1, 0] * 20
    paired = compare_paired(a, b)
    independent = compare_rates(sum(a), len(a), sum(b), len(b))
    paired_width = paired["upper"] - paired["lower"]
    independent_width = independent["diff_high"] - independent["diff_low"]
    assert paired_width == pytest.approx(independent_width, rel=0.15)


def test_compare_paired_identical_arms_has_zero_difference_and_contains_zero() -> None:
    result = compare_paired([1, 0, 1, 0], [1, 0, 1, 0])
    assert result["difference"] == 0.0
    assert result["lower"] <= 0.0 <= result["upper"]
    assert result["excludes_zero"] is False


def test_compare_paired_twelve_identical_pairs_has_nonzero_interval() -> None:
    result = compare_paired([1] * 12, [1] * 12)
    # The marginal Wilson interval for 12/12 is [0.757506, 1]; zero discordance
    # sets phi correction to 0, so each difference bound is about +/-0.242494.
    assert result["lower"] == pytest.approx(-0.2424940066552408)
    assert result["upper"] == pytest.approx(0.2424940066552408)
    assert result["lower"] < result["upper"]


def test_compare_paired_one_discordant_pair_out_of_twelve_contains_zero() -> None:
    result = compare_paired([1] * 11 + [0], [1] * 12)
    assert result["difference"] == pytest.approx(-1 / 12)
    assert result["b_only"] == 1
    assert result["lower"] <= 0.0 <= result["upper"]


def test_compare_paired_interval_stays_within_unit_difference_range() -> None:
    for n in range(1, 5):
        for a_mask in range(1 << n):
            for b_mask in range(1 << n):
                a = [(a_mask >> index) & 1 for index in range(n)]
                b = [(b_mask >> index) & 1 for index in range(n)]
                result = compare_paired(a, b)
                assert -1.0 <= result["lower"] <= result["upper"] <= 1.0


