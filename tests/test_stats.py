def _record(
    *,
    winner: int | None,
    length: int = 10,
    collapses: int = 0,
    observe_moves: int = 0,
    spread_moves: int = 0,
    termination: str = "no_pieces",
    condition: str = "unit",
) -> dict:
    """Build a minimal decoded record shaped like a real JSONL line."""
    return {
        "condition": condition,
        "winner": winner,
        "termination": termination,
        "length": length,
        "collapses": collapses,
        "observe_moves": observe_moves,
        "spread_moves": spread_moves,
    }


def test_summarize_empty_is_legal_and_undefined() -> None:
    """An empty batch must not raise; every interval must be flagged undefined."""
    summary = summarize([])
    assert summary["n_games"] == 0
    for metric in summary["metrics"].values():
        assert metric.defined is False
    assert summary["rates"]["mean_length"] == 0.0
    assert summary["rates"]["stdev_length"] == 0.0


def test_summarize_counts_wins_draws_and_terminations() -> None:
    records = [
        _record(winner=0, length=8, termination="no_pieces"),
        _record(winner=1, length=12, termination="no_pieces"),
        _record(winner=None, length=20, termination="ply_limit"),
        _record(winner=0, length=6, collapses=1, observe_moves=1),
    ]
    summary = summarize(records)
    assert summary["n_games"] == 4
    assert summary["metrics"]["win_rate_p0"].successes == 2
    assert summary["metrics"]["win_rate_p1"].successes == 1
    assert summary["metrics"]["draw_rate"].successes == 1
    assert summary["metrics"]["collapse_rate"].successes == 1
    assert summary["metrics"]["observe_usage"].successes == 1
    assert summary["rates"]["mean_length"] == pytest.approx(11.5)
    assert summary["termination_counts"] == {"no_pieces": 3, "ply_limit": 1}


def test_summarize_draw_rate_uses_full_denominator() -> None:
    """A draw must not count as a win for either player."""
    records = [_record(winner=None) for _ in range(5)]
    summary = summarize(records)
    assert summary["metrics"]["draw_rate"].point == 1.0
    assert summary["metrics"]["win_rate_p0"].point == 0.0
    assert summary["metrics"]["win_rate_p1"].point == 0.0


def test_summarize_stdev_uses_sample_denominator() -> None:
    """``ddof = 1``: two values 8 and 12 give sd 2sqrt(2), not 2."""
    summary = summarize([_record(winner=0, length=8), _record(winner=1, length=12)])
    assert summary["rates"]["stdev_length"] == pytest.approx(2.0 * math.sqrt(2.0))


def test_summarize_stdev_zero_for_single_game() -> None:
    """One game has no sample variance; report 0.0 rather than raising."""
    summary = summarize([_record(winner=0)])
    assert summary["rates"]["stdev_length"] == 0.0


def test_summarize_rejects_bad_reference_player() -> None:
    with pytest.raises(ValueError):
        summarize([_record(winner=0)], reference_player=2)


def test_summarize_labels_single_condition_only() -> None:
    records = [_record(winner=0, condition="alpha"), _record(winner=1, condition="alpha")]
    assert summarize(records)["condition"] == "alpha"

    mixed = [_record(winner=0, condition="alpha"), _record(winner=1, condition="beta")]
    assert summarize(mixed)["condition"] is None


