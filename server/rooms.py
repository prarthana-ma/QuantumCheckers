def _new_token(prefix: str) -> str:
    """Opaque identifier from the OS CSPRNG (not ``random``; C3 keeps that stream free)."""
    return f"{prefix}-{secrets.token_hex(4)}"


@dataclass
class Seat:
    """One seat at a room's table."""

    number: int
    player_id: str | None = None
    label: str = "open"
    is_agent: bool = False

    @property
    def filled(self) -> bool:
        return self.player_id is not None or self.is_agent


@dataclass
class Room:
    """One in-memory match.

    The room owns the engine, the authoritative state, the seats and the optional
    game-over log callback. It performs no I/O and no awaiting: the FastAPI layer owns
    the sockets, and this class stays unit-testable on its own.
    """

    game_id: str
    level: int
    mode: str
    seed: int
    board_size: int = 4
    max_plies: int = 200
    on_game_over: Callable[[GameRecord], None] | None = None
    #: **Live-game hardware injection.** A sampler (see :mod:`server.quantum_measure`)
    #: makes every collapse in this room resolve on IBM Quantum hardware. ``None`` means
    #: the room is built with credentials absent and must be resolved from the
    #: environment in :meth:`__post_init__`; a room with neither runs the normal seeded
    #: game. It is never set on the research/experiment engine, which lives outside
    #: this module.
    quantum_sampler: IBMHardwareSampler | None = None
    paper_rules: bool = False
    #: Called (from a worker thread) when a hardware measurement starts, so the async
    #: layer can broadcast a pending frame. Never called for ordinary moves.
    on_quantum_change: Callable[["Room"], None] | None = None

    #: Seats by number. Seat 0 always exists; ``online`` opens seat 1 for a joiner.
    seats: dict[int, Seat] = field(default_factory=dict)
    #: Agents seated at the table, by seat number (Phase 3 difficulty tiers).
    agents: dict[int, Agent] = field(default_factory=dict)
    engine: DeterministicToyEngine = field(init=False)
    state: GameState = field(init=False)
    status: str = field(default="waiting", init=False)
    outcome: GameOutcome | None = field(default=None, init=False)
    started_at: float = field(default=0.0, init=False)
    finished_at: float = field(default=0.0, init=False)

    #: Log accumulation, mirroring ``qcheckers.experiment.runner.play``.
    _turns: list[TurnRecord] = field(default_factory=list, init=False)
    _counts: dict[str, int] = field(default_factory=dict, init=False)
    _collapses: int = field(default=0, init=False)
    _collapse_pieces: set[str] = field(default_factory=set, init=False)

    #: True only while a hardware measurement is in flight, so the client can show a
    #: pending state. Never persisted; the room is in memory only.
    quantum_pending: bool = field(default=False, init=False)
    #: Provenance of the most recent hardware collapse (backend, job id, bitstring).
    last_quantum: Provenance | None = field(default=None, init=False)
    _staged_quantum: Provenance | None = field(default=None, init=False)

    def __post_init__(self) -> None:
        if self.level not in SUPPORTED_LEVELS:
            raise ValueError(f"level must be one of {SUPPORTED_LEVELS}; got {self.level!r}")
        if self.mode not in MODES:
            raise ValueError(f"mode must be one of {MODES}; got {self.mode!r}")
        if self.board_size < 4:
            raise ValueError(f"board_size must be >= 4; got {self.board_size!r}")

        # Voluntary Observe is the extension condition and the stage-2 reward: level 1
        # teaches the split alone (a level-1 spread piece can still be resolved by a
        # capture), and resolving one by choice -- Observe, or a targeted rejoin --
        # arrives with stage 2. The Hard tier has it at every level, because that is
        # what makes it Hard. Easy/Medium stay on the reproduced mechanics so the tiers
        # are a clean strength ladder (Phase 3 acceptance).
        allow_observe = (self.mode in ("local", "online") and self.level >= 2) or (
            self.mode == "ai-hard"
        )

        # Hardware mode: an explicitly injected sampler wins; otherwise build one only
        # when IBM credentials are configured. No credentials -> None -> the ordinary
        # seeded game, exactly as before this feature existed.
        if self.quantum_sampler is None and os.environ.get(
            "QCHECKERS_DISABLE_HARDWARE"
        ) not in ("1", "true", "yes"):
            self.quantum_sampler = sampler_from_env()

        self.engine = DeterministicToyEngine(
            seed=self.seed,
            level=self.level,
            allow_observe=allow_observe,
            board_size=self.board_size,
            max_plies=self.max_plies,
            # Level 4 is the decoherence stage; the flag is what keeps that rule out of
            # every other level and out of every experiment.
            decoherence=(self.level == 4),
            # Only ever set for a live room; the batch runner and every offline unit
            # engine leave this None. See the engine docstring for the contract.
            sampler=self._hardware_sample if self.quantum_sampler is not None else None,
            live_rules=True,
        )
        if self.paper_rules:
            self.engine = PaperQuantumEngine(
                seed=self.seed, level=self.level, board_size=self.board_size,
                max_plies=self.max_plies,
                sampler=self._hardware_sample if self.quantum_sampler is not None else None,
            )
        self.state = self.engine.initial_state()
        self._counts = {"move": 0, "capture": 0, "spread": 0, "rejoin": 0, "observe": 0, "merge": 0}

        self.seats = {0: Seat(number=0, label="p0", player_id=_new_token("p"))}
        if self.mode == "online":
            self.seats[1] = Seat(number=1, label="p1")
        elif self.mode == "local":
            self.seats[1] = Seat(number=1, label="local", player_id=self.seats[0].player_id)
        else:  # ai-easy / ai-medium / ai-hard
            if self.paper_rules and self.mode != "ai-easy":
                budget = 200 if self.mode == "ai-medium" else 400
                agent = LiveMCTSAgent(self.engine, seed=self.seed, iterations=budget, tree_depth=4, rollout_steps=8, name=f"live-mcts-{budget}")
            else:
                agent = make_agent(AI_AGENT_KINDS[self.mode], self.engine, self.seed)
            self.seats[1] = Seat(number=1, label=agent.name, player_id=None, is_agent=True)
            self.agents[1] = agent

        self.started_at = time.time()
        self.status = "waiting" if not self._all_seats_filled() else "playing"

    # -- seats -------------------------------------------------------------

    def _all_seats_filled(self) -> bool:
        return all(seat.filled for seat in self.seats.values())

    @property
    def creator_id(self) -> str:
        """Seat 0's token: what ``POST /api/game`` hands back to the creating client."""
        return str(self.seats[0].player_id)

    def seat_number_of(self, player_id: str | None) -> int | None:
        """Seat held by ``player_id``, or ``None`` for an empty/unknown token."""
        if not player_id:
            return None
        for number, seat in self.seats.items():
            if seat.player_id == player_id:
                return number
        return None

    def claim(self, player_id: str | None, label: str | None = None) -> int | None:
        """Seat a (re)joining client.

        Reclaims an existing seat when the token is recognised (reconnect). Otherwise
        takes the first open seat; a full room returns ``None``, which the caller treats
        as spectator (read-only) per the frozen protocol.
        """
        existing = self.seat_number_of(player_id)
        if existing is not None:
            if label:
                self.seats[existing].label = label
            return existing

        for number, seat in sorted(self.seats.items()):
            if not seat.filled:
                seat.player_id = player_id or _new_token("p")
                if label:
                    seat.label = label
                if self._all_seats_filled():
                    self.status = "playing"
                return number

        if self.mode == "local":
            # Local play is one browser holding both seats; the creator token already
            # owns them, so a second token is a spectator.
            return None
        return None

    # -- views -------------------------------------------------------------

    def view(self, player_id: str | None) -> dict[str, Any]:
        """The ``StateUpdate`` payload for one viewer (seats differ only in ``you``)."""
        seat = self.seat_number_of(player_id)
        legal: list[dict[str, Any]] = []
        if self.status == "playing" and (seat is None or self._may_move(seat)):
            legal = [action.to_json() for action in self.engine.legal_actions(self.state)]
        # Level-4 coherence, keyed by the spread piece's origin square ("row,col"), so
        # the game client can render a per-square counter. Empty when decoherence is off.
        coherence: dict[str, int] = {}
        for piece in self.state.pieces:
            ticks = dict(self.state.coherence).get(piece.piece_id) if self.paper_rules else piece.coherence
            if piece.is_spread and ticks is not None and piece.sites:
                origin = piece.sites[0][0]
                coherence[f"{origin[0]},{origin[1]}"] = ticks

        last_event: dict[str, Any] | None = None
        if self.state.last_event is not None:
            event = self.state.last_event
            last_event = event.to_json()
            # Compact aliases matching the frozen protocol samples. ``sampled`` stays
            # authoritative; ``kept``/``by`` are the same information under the names
            # the sample payload uses.
            last_event["kind"] = "collapse"
            last_event["kept"] = list(event.sampled)
            last_event["by"] = event.cause
            # Hardware provenance for the collapse, when this room ran on a QPU. Kept on
            # the event so the browser can name the backend that resolved this piece.
            if self.last_quantum is not None:
                last_event["quantum"] = self.last_quantum.to_json()

        payload: dict[str, Any] = {
            "type": "StateUpdate",
            "board": self.engine.render(self.state),
            "occupancy": self.engine.render(self.state)["occupancy"] if self.paper_rules else board_chances(self.state, self.engine.board_size),
            "coherence": coherence,
            "turn": self.state.turn,
            "phase": self.status,
            "last_event": last_event,
            "quantum": self._quantum_view(),
            "quantum_pending": self.quantum_pending,
            "last_action": (
                self.state.history[-1].to_json() if self.state.history else None
            ),
            "legal": legal,
            "you": seat,
            "ply": self.state.ply,
            "status": self.status,
            "mode": self.mode,
        }
        if player_id is not None:
            # Only ever sent to the socket that holds (or is claiming) the seat, so a
            # reconnect can present the same token. A tokenless view -- the REST GET and
            # spectators -- never carries somebody else's token.
            payload["player_id"] = player_id
        return payload

    def _quantum_view(self) -> dict[str, Any]:
        """The small quantum block every StateUpdate carries.

        ``enabled`` says whether this room resolves collapses on hardware; ``backend``
        names the device (best-known before the first job, resolved after); ``last`` is
        the provenance of the most recent hardware collapse. No credentials here.
        """
        return {
            "enabled": self.quantum_sampler is not None,
            "pending": self.quantum_pending,
            "backend": (
                self.quantum_sampler.backend_label
                if self.quantum_sampler is not None
                else None
            ),
            "last": self.last_quantum.to_json() if self.last_quantum is not None else None,
        }

    def _hardware_sample(
        self, sites: tuple[tuple[Square, float], ...]
    ) -> tuple[Square, float]:
        """Bridge the engine's collapse hook to the hardware sampler.

        Runs inside ``engine.apply`` -- on the worker thread the async layer owns -- so it
        may block on the QPU. It flips the pending flag for that window and records the
        resulting provenance. A raised :class:`~server.quantum_measure.QuantumMeasurementError`
        propagates through ``apply`` before any new state is constructed, so the room is
        left untouched and the move is refused with a clear error.
        """
        assert self.quantum_sampler is not None  # guarded by the engine wiring
        self.quantum_pending = True
        self._notify_quantum()
        try:
            result = self.quantum_sampler(sites)
        finally:
            self.quantum_pending = False
        self._staged_quantum = self.quantum_sampler.last
        return result

    def _notify_quantum(self) -> None:
        """Tell the async layer a measurement is starting; never let it break a turn."""
        if self.on_quantum_change is None:
            return
        try:
            self.on_quantum_change(self)
        except Exception:  # pragma: no cover - a broadcast hiccup must not fail a move
            pass

    def _may_move(self, seat: int) -> bool:
        """Whether this seat may send a move right now (seat checks live in one place)."""
        if self.status != "playing":
            return False
        if self.mode == "local":
            return True
        return seat == self.state.turn

    # -- moves -------------------------------------------------------------

    def move(self, player_id: str, message: Mapping[str, Any]) -> None:
        """Resolve and apply one client move.

        Raises :class:`ProtocolError` *without touching the state* when the move is
        refused, which is what makes "illegal move -> Error, state unchanged" true.
        AI replies are not played here: the caller drives :meth:`play_ai_ply` so it can
        broadcast the human's move before the reply.
        """
        if self.status == "over":
            raise ProtocolError("this game is over", "game_over")

        seat = self.seat_number_of(player_id)
        if seat is None:
            raise ProtocolError("this connection holds no seat", "not_seated")
        if not self._may_move(seat):
            raise ProtocolError("it is not your turn", "not_your_turn")

        action = resolve_action(self.engine, self.state, message)
        try:
            self._apply(action)
        except PaperRuleError as exc:
            raise ProtocolError(str(exc), "quantum_rule_error") from exc

    def ai_to_move(self) -> bool:
        """True when seat-to-move is a seated agent and the game is still running."""
        return (
            self.status == "playing"
            and self.state.turn in self.agents
            and bool(self.engine.legal_actions(self.state))
        )

    def play_ai_ply(self) -> None:
        """Apply exactly one agent move for the seat to move.

        Raises :class:`ProtocolError` if the agent proposes something illegal -- that is
        a server bug, surfaced rather than written into a log.
        """
        if not self.ai_to_move():  # pragma: no cover - caller checks first
            return
        agent = self.agents[self.state.turn]
        legal = self.engine.legal_actions(self.state)
        action = agent.decide(self.state, legal)
        if action not in legal:
            raise ProtocolError(
                f"seated agent {agent.name!r} proposed an illegal move", "agent_error"
            )
        self._apply(action)

    def resign(self, player_id: str) -> None:
        """End the game with the resigning seat losing."""
        if self.status == "over":
            raise ProtocolError("this game is over", "game_over")
        seat = self.seat_number_of(player_id)
        if seat is None:
            raise ProtocolError("this connection holds no seat", "not_seated")
        self.status = "over"
        self.outcome = GameOutcome(winner=1 - seat, reason="resign")
        self._finalise()

    # -- internals ---------------------------------------------------------

    def _apply(self, action: Action) -> None:
        """Apply one legal action, recording it exactly the way the runner does."""
        mover = self.state.turn
        self._staged_quantum = None
        try:
            step = self.engine.apply(self.state, action)
        except PaperRuleError as exc:
            self._staged_quantum = None
            raise ProtocolError(str(exc), "quantum_rule_error") from exc
        except Exception:
            self._staged_quantum = None
            raise
        if self._staged_quantum is not None:
            self.last_quantum = self._staged_quantum
        self._staged_quantum = None
        self._counts[action.kind] = self._counts.get(action.kind, 0) + 1
        for event in step.events:
            self._collapses += 1
            self._collapse_pieces.add(event.piece_id)
        self._turns.append(
            TurnRecord(
                ply=len(self._turns),
                player=mover,
                action=action,
                board_after=board_snapshot(self.engine, step.state),
                events=tuple(_event_to_json(event) for event in step.events),
            )
        )
        self.state = step.state

        outcome = self.engine.outcome(self.state)
        if outcome is not None:
            self.status = "over"
            self.outcome = outcome
            self._finalise()

    def _finalise(self) -> None:
        """Build the frozen-format record and hand it to the writer, once."""
        if self.finished_at:  # pragma: no cover - defensive double-call guard
            return
        self.finished_at = time.time()
        if self.on_game_over is None:
            return

        outcome = self.outcome or GameOutcome(winner=None, reason="ply_limit")
        record = GameRecord(
            game_id=self.game_id,
            seed=self.seed,
            condition=f"L{self.level}-{self.mode}",
            engine=self.engine.name,
            level=self.level,
            allow_observe=self.engine.allow_observe,
            max_plies=self.engine.max_plies,
            players={
                number: seat.label for number, seat in sorted(self.seats.items())
            },
            winner=outcome.winner,
            termination=outcome.reason,
            length=self.state.ply,
            collapses=self._collapses,
            collapse_pieces=tuple(sorted(self._collapse_pieces)),
            observe_moves=self._counts["observe"],
            spread_moves=self._counts["spread"],
            capture_moves=self._counts["capture"],
            board_moves=self._counts["move"],
            rejoin_moves=self._counts["rejoin"],
            final_board=board_snapshot(self.engine, self.state),
            turns=tuple(self._turns),
        )
        self.on_game_over(record)


def _event_to_json(event: Any) -> dict[str, Any]:
    """Collapse event -> flattened JSON, matching the runner's log encoding."""
    payload = event.to_json()
    payload["chances"] = [
        [square[0][0], square[0][1], square[1]] for square in payload["chances"]
    ]
    payload["sampled"] = list(payload["sampled"])
    return payload


