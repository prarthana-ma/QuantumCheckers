"""In-memory game rooms for the Quantum Checkers server.

Owner: **P5 -- rules, engine, harness and batches** (server-authoritative play), with
**P1** owning the agent tiers the server seats.

Design contract (see ``docs/PROTOCOL.md``, frozen):

* **C1 -- the engine is the single source of truth.** A client message is resolved by
  finding the matching action in ``engine.legal_actions(state)`` and applying it. There
  is no rule logic in this module beyond that lookup, so the codebase still contains
  exactly one rules implementation.
* **C3 -- determinism.** A room's seed is recorded on the room and written into the game
  record, so any server game can be regenerated by the headless runner.
* Nothing here is persisted: rooms live in memory and die with the process (brief:
  no persistent DB, no accounts).

The AI seats are the Phase 3 difficulty tiers: ``ai-easy`` is the seeded random agent,
``ai-medium`` the MCTS baseline, and ``ai-hard`` the probability-aware agent with the
voluntary Observe mechanic enabled. Every AI agent is seeded from the room seed, so a
server game is reproducible too.
"""

