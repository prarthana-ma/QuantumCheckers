def parse_square(value: Any, field_name: str = "square") -> Square:
    """Parse a square from ``[row, col]`` or an algebraic string like ``"c3"``.

    Arrays are what the browser client sends; the algebraic form is the compact style
    in the frozen protocol samples (``{"from":"c3","to":"d4"}``). The mapping is
    explicit because two conventions exist: the letter is the **column** index
    (``a`` = 0) and the number is the **row** index plus one, so ``"c3"`` is
    ``(2, 2)``. Anything else raises :class:`ProtocolError`.
    """
    if isinstance(value, str):
        text = value.strip().lower()
        if len(text) >= 2 and text[0].isalpha() and text[1:].isdigit():
            return (int(text[1:]) - 1, ord(text[0]) - ord("a"))
        raise ProtocolError(
            f"{field_name} must be [row, col] or a square like 'c3'; got {value!r}"
        )
    if not isinstance(value, (list, tuple)) or len(value) != 2:
        raise ProtocolError(f"{field_name} must be [row, col]; got {value!r}")
    try:
        row, col = int(value[0]), int(value[1])
    except (TypeError, ValueError) as exc:
        raise ProtocolError(f"{field_name} must contain integers; got {value!r}") from exc
    return (row, col)


def resolve_action(
    engine: DeterministicToyEngine, state: GameState, message: Mapping[str, Any]
) -> Action:
    """Find the legal engine action a protocol message names.

    This is the *whole* of the server's rule handling. Every branch filters
    ``engine.legal_actions(state)`` and returns one element of it; if nothing matches,
    the move is refused and the caller leaves the state untouched.
    """
    kind = message.get("type")
    legal = engine.legal_actions(state)

    if isinstance(engine, PaperQuantumEngine):
        return _resolve_paper_action(state, legal, message)

    if kind == "Move":
        origin = parse_square(message.get("from"), "from")
        target = parse_square(message.get("to"), "to")
        for action in legal:
            if isinstance(action, (MoveAction, CaptureAction)):
                if action.origin == origin and action.target == target:
                    return action
        raise ProtocolError(
            f"no legal move from {origin} to {target}", "illegal_move"
        )

    if kind == "SplitMove":
        origin = parse_square(message.get("from"), "from")
        candidates = [
            action
            for action in legal
            if isinstance(action, SpreadAction) and action.origin == origin
        ]
        if not candidates:
            raise ProtocolError(f"no legal split from {origin}", "illegal_move")
        action = candidates[0]
        targets = message.get("targets")
        if targets is not None:
            if not isinstance(targets, Sequence) or isinstance(targets, (str, bytes)):
                raise ProtocolError("targets must be a list of [row, col]", "bad_request")
            wanted = {parse_square(entry, "targets[]") for entry in targets}
            offered = {square for square, _ in action.sites if square != action.origin}
            if wanted != offered:
                raise ProtocolError(
                    "split targets do not match the engine's distribution; "
                    f"engine offers {sorted(offered)}",
                    "illegal_split",
                )
        return action

    if kind == "ObserveMove":
        square = parse_square(message.get("square"), "square")
        for action in legal:
            if isinstance(action, ObserveAction):
                try:
                    piece = state.piece(action.piece_id)
                except KeyError:  # pragma: no cover - engine list is self-consistent
                    continue
                if square in piece.squares:
                    return action
        raise ProtocolError(
            f"no legal observe on {square}", "illegal_move"
        )

    if kind == "MergeMove":
        return _resolve_merge(state, legal, message)

    raise ProtocolError(f"unknown move type {kind!r}", "unknown_type")


def _resolve_paper_action(state: Any, legal: Iterable[Any], message: Mapping[str, Any]) -> Any:
    """Match a paper-engine action exactly; legality stays in the engine."""
    kind = message.get("type")
    actions = list(legal)
    identity = message.get("piece")
    if identity is not None:
        if not isinstance(identity, str):
            raise ProtocolError("piece must be an original piece identifier", "bad_request")
        actions = [action for action in actions if action.piece_id == identity]
    if kind == "Move":
        origin, target = parse_square(message.get("from"), "from"), parse_square(message.get("to"), "to")
        for action in actions:
            if action.kind in ("move", "capture") and action.origin == origin and action.target == target:
                return action
    elif kind == "SplitMove":
        origin = parse_square(message.get("from"), "from")
        offered = [action for action in actions if action.kind == "spread" and action.origin == origin]
        raw = message.get("targets")
        if raw is None and len(offered) == 1:
            return offered[0]
        if not isinstance(raw, (list, tuple)) or len(raw) != 2:
            raise ProtocolError("select exactly two legal split destinations", "bad_request")
        targets = [parse_square(entry, "targets[]") for entry in raw]
        for action in offered:
            if len(set(targets)) == 2 and set(action.targets) == set(targets):
                return action
    elif kind == "ObserveMove":
        square = parse_square(message.get("square"), "square")
        for action in actions:
            if action.kind == "observe" and square in state.piece(action.piece_id).squares:
                return action
    elif kind == "MergeMove":
        raw = message.get("sources")
        target = parse_square(message.get("target"), "target")
        if not isinstance(raw, (list, tuple)) or len(raw) != 2:
            raise ProtocolError("select two branches of the same original piece", "bad_request")
        sources = [parse_square(entry, "sources[]") for entry in raw]
        for action in actions:
            if action.kind == "merge" and action.piece_id == message.get("piece") and action.target == target and set(sources) == {action.origin, action.other_origin}:
                return action
    else:
        raise ProtocolError(f"unknown move type {kind!r}", "unknown_type")
    raise ProtocolError("that action is not in the current legal move list", "illegal_move")


def _resolve_merge(
    state: GameState, legal: Iterable[Action], message: Mapping[str, Any]
) -> Action:
    """Resolve ``MergeMove`` to a level-3 ``MergeAction`` or a level-2 ``RejoinAction``.

    ``pieces`` (a pair of ids) selects an engine merge; a single ``piece`` selects one
    side of a merge and is also accepted for a rejoin. An optional ``target`` narrows a
    rejoin to a specific square. The first match in the engine's stable order wins, so
    two identical messages never produce different actions.
    """
    named = message.get("pieces")
    piece_id = message.get("piece")
    ids: list[str] = []
    if isinstance(named, Sequence) and not isinstance(named, (str, bytes)):
        ids = [str(entry) for entry in named]
    elif piece_id is not None:
        ids = [str(piece_id)]

    target = parse_square(message["target"], "target") if "target" in message else None

    merges = [action for action in legal if isinstance(action, MergeAction)]
    rejoins = [action for action in legal if isinstance(action, RejoinAction)]

    if len(ids) >= 2:
        wanted = set(ids)
        for action in merges:
            if {action.piece_id, action.other_piece_id} == wanted:
                return action
    elif len(ids) == 1:
        for action in merges:
            if ids[0] in (action.piece_id, action.other_piece_id):
                return action
        for action in rejoins:
            if action.piece_id == ids[0] and (target is None or action.target == target):
                return action
    elif target is not None:
        for action in rejoins:
            if action.target == target:
                return action

    raise ProtocolError("no legal merge or rejoin matches that request", "illegal_move")


