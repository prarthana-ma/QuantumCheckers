#: Levels the server will open a room for. Level 3 (merge) and level 4 (decoherence) are
#: game-only: they are playable here and refused by the batch runner.
SUPPORTED_LEVELS: tuple[int, ...] = (0, 1, 2, 3, 4)

#: Human seat-play modes.
MODES: tuple[str, ...] = ("local", "online", "ai-easy", "ai-medium", "ai-hard")

#: Which agent kind sits in seat 1 for each AI mode. ``hard`` is the game tier:
#: probability-aware search with the voluntary Observe policy enabled.
AI_AGENT_KINDS: Mapping[str, str] = {
    "ai-easy": "random",
    "ai-medium": "mcts",
    "ai-hard": "hard",
}


class ProtocolError(Exception):
    """A client message the protocol refuses.

    Carries a machine-readable ``code`` so the client can react without string-matching.
    """

    def __init__(self, message: str, code: str = "bad_request") -> None:
        super().__init__(message)
        self.code = code


