class RoomRegistry:
    """In-memory room table. One process, no persistence (brief: memory rooms only)."""

    def __init__(self, log_path: str | Path | None = None, *, paper_rules: bool = False) -> None:
        self._rooms: dict[str, Room] = {}
        self.log_path = Path(log_path) if log_path is not None else None
        self.paper_rules = paper_rules

    def create(
        self,
        *,
        level: int,
        mode: str,
        seed: int | None = None,
        board_size: int = 4,
        max_plies: int = 200,
    ) -> Room:
        """Open a room and register it under a fresh lobby code."""
        if level not in SUPPORTED_LEVELS:
            raise ValueError(f"level must be one of {SUPPORTED_LEVELS}; got {level!r}")
        if mode not in MODES:
            raise ValueError(f"mode must be one of {MODES}; got {mode!r}")
        resolved_seed = secrets.randbelow(2**31) if seed is None else int(seed)
        game_id = _new_token("qk")
        room = Room(
            game_id=game_id,
            level=level,
            mode=mode,
            seed=resolved_seed,
            board_size=board_size,
            max_plies=max_plies,
            on_game_over=self._writer,
            paper_rules=self.paper_rules,
        )
        self._rooms[game_id] = room
        return room

    def _writer(self, record: GameRecord) -> None:
        """Append a finished server game to the server log, when logging is on."""
        if self.log_path is None:
            return
        append_jsonl(self.log_path, record)

    def get(self, game_id: str) -> Room | None:
        return self._rooms.get(game_id)

    def require(self, game_id: str) -> Room:
        room = self._rooms.get(game_id)
        if room is None:
            raise KeyError(game_id)
        return room

    def __len__(self) -> int:
        return len(self._rooms)


